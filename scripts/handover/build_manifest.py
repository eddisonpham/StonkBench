#!/usr/bin/env python3
"""Rebuild ``handover/MANIFEST.json`` (path, bytes, sha256, kind, model, L).

    python3 scripts/handover/build_manifest.py
"""

from __future__ import annotations

import collections
import hashlib
import json
import re
from datetime import datetime, timezone
from pathlib import Path

CODE_DIR = Path(__file__).resolve().parent
REPO = CODE_DIR.parents[1]
HANDOVER = REPO / "handover"

from load_handover import MODEL_TYPES, SEQUENCE_LENGTHS  # noqa: E402

CELL_RE = re.compile(r"(?P<model>[a-z_]+)_seq(?P<length>\d+)")
KINDS = {
    "01_model_checkpoints": "checkpoint",
    "02_generated_outputs": "generated_output",
    "03_ground_truth": "ground_truth",
    "04_evaluation_results": "results",
}


def classify(rel: Path) -> str:
    top = rel.parts[0]
    if rel.suffix in (".md",):
        return "doc"
    if rel.suffix in (".csv",):
        return "table"
    return KINDS.get(top, "other")


def sha256_of(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for block in iter(lambda: fh.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def main() -> int:
    files = []
    for path in sorted(p for p in HANDOVER.rglob("*") if p.is_file()):
        rel = path.relative_to(HANDOVER)
        if rel.as_posix() == "MANIFEST.json":
            continue
        rec = {
            "path": rel.as_posix(),
            "kind": classify(rel),
            "bytes": path.stat().st_size,
            "sha256": sha256_of(path),
            "source": "generated by the StonkBench evaluation pipeline",
        }
        m = CELL_RE.search(path.stem)
        if m and m.group("model") in MODEL_TYPES:
            rec["model"] = m.group("model")
            rec["sequence_length"] = int(m.group("length"))
        elif "model" not in rec:
            for model in MODEL_TYPES:
                if model in path.parts:
                    rec["model"] = model
                    break
        files.append(rec)

    manifest = {
        "bundle": "handover",
        "generated_by": "scripts/handover/build_manifest.py",
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "repo": str(REPO),
        "models": sorted(MODEL_TYPES),
        "model_types": MODEL_TYPES,
        "sequence_lengths": list(SEQUENCE_LENGTHS),
        "n_files": len(files),
        "total_bytes": sum(r["bytes"] for r in files),
        "files_by_kind": dict(collections.Counter(r["kind"] for r in files)),
        "files_by_top_level": dict(collections.Counter(r["path"].split("/")[0] for r in files)),
        "files": files,
    }
    (HANDOVER / "MANIFEST.json").write_text(json.dumps(manifest, indent=1, sort_keys=True))
    print(f"wrote {HANDOVER / 'MANIFEST.json'}")
    print(f"  {manifest['n_files']} files, {manifest['total_bytes'] / 1048576:.1f} MB")
    print(f"  kinds: {manifest['files_by_kind']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
